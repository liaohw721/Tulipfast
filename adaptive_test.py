"""Benchmark vision-feature caching policies on a synthetic frame sequence.

This is a CPU-only proof of concept. Frames are generated by adding noise to
one transformed photo; they are not a real camera/video sequence.
"""

import argparse
import statistics
import time
from datetime import datetime
from pathlib import Path

import pandas as pd
import torch
import torchvision
from PIL import Image
from torchvision.models import ResNet18_Weights, resnet18


PROJECT_DIR = Path(__file__).resolve().parent
STRATEGIES = ("Always Refresh", "Fixed Rate", "Adaptive Cache")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Compare always-refresh, fixed-rate, and adaptive feature caching."
    )
    parser.add_argument("--frames", type=int, default=30, help="Number of synthetic frames (default: 30).")
    parser.add_argument("--trials", type=int, default=5, help="Trials per strategy (default: 5).")
    parser.add_argument(
        "--refresh-interval",
        type=int,
        default=10,
        help="Refresh every N frames for Fixed Rate (default: 10).",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.02,
        help="Adaptive refresh threshold on mean absolute difference (default: 0.02).",
    )
    parser.add_argument("--num-threads", type=int, default=2, help="PyTorch CPU threads (default: 2).")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for frame generation (default: 42).")
    parser.add_argument(
        "--image",
        default="test_image.jpg",
        help="Image path; relative paths are resolved from the project folder.",
    )
    parser.add_argument(
        "--results-dir",
        default="results",
        help="Output directory; relative paths are resolved from the project folder.",
    )
    args = parser.parse_args()

    if args.frames < 1:
        parser.error("--frames must be at least 1.")
    if args.trials < 1:
        parser.error("--trials must be at least 1.")
    if args.refresh_interval < 1:
        parser.error("--refresh-interval must be at least 1.")
    if args.threshold < 0:
        parser.error("--threshold cannot be negative.")
    if args.num_threads < 1:
        parser.error("--num-threads must be at least 1.")
    return args


def resolve_project_path(path_value):
    """Resolve absolute paths as-is and relative paths from the project folder."""
    path = Path(path_value).expanduser()
    return path if path.is_absolute() else PROJECT_DIR / path


def build_frame_sequence(base_tensor, num_frames):
    """Create deterministic-in-process perturbations of one normalized image tensor."""
    frames = []
    for i in range(num_frames):
        noise = torch.randn_like(base_tensor) * (i / num_frames) * 0.1
        frames.append((base_tensor + noise).unsqueeze(0))
    return frames


def execute_strategy(
    strategy,
    model,
    frames,
    reference_features,
    refresh_interval=10,
    threshold=0.02,
):
    """Run one caching policy and calculate feature errors outside the timed region."""
    if strategy not in STRATEGIES:
        raise ValueError(f"Unknown strategy: {strategy}")
    if refresh_interval < 1:
        raise ValueError("refresh_interval must be at least 1.")
    if threshold < 0:
        raise ValueError("threshold cannot be negative.")
    if len(frames) != len(reference_features):
        raise ValueError("frames and reference_features must have the same length.")
    if not frames:
        raise ValueError("At least one frame is required.")

    last_frame = None
    cached_features = None
    refreshes = 0
    outputs = []

    start = time.perf_counter()
    with torch.inference_mode():
        for i, frame in enumerate(frames):
            if strategy == "Always Refresh":
                refresh = True
            elif cached_features is None:
                # The first frame must always populate the cache.
                refresh = True
            elif strategy == "Fixed Rate":
                refresh = i % refresh_interval == 0
            else:  # Adaptive Cache
                difference = torch.mean(torch.abs(frame - last_frame)).item()
                refresh = difference > threshold

            if refresh:
                cached_features = model(frame)
                last_frame = frame
                refreshes += 1

            outputs.append(cached_features)

    total_ms = (time.perf_counter() - start) * 1000

    # Correctness checks are intentionally excluded from the latency measurement.
    frame_errors = []
    max_errors = []
    with torch.inference_mode():
        for output, reference in zip(outputs, reference_features):
            diff = torch.abs(output - reference)
            frame_errors.append(diff.mean().item())
            max_errors.append(diff.max().item())

    frame_count = len(frames)
    return {
        "Strategy": strategy,
        "Total_ms": total_ms,
        "Per_Frame_ms": total_ms / frame_count,
        "Refreshes": refreshes,
        "Cache_Hits": frame_count - refreshes,
        "Hit_Rate": (frame_count - refreshes) / frame_count,
        "Mean_Feature_Error": statistics.mean(frame_errors),
        "Max_Feature_Error": max(max_errors),
    }


def main():
    args = parse_args()
    torch.manual_seed(args.seed)
    torch.set_num_threads(args.num_threads)

    image_path = resolve_project_path(args.image)
    if not image_path.is_file():
        raise FileNotFoundError(
            f"Image not found: {image_path}\n"
            "Place test_image.jpg in the project folder or pass --image with a valid path."
        )

    # Load a pretrained vision encoder. The first run may download weights.
    weights = ResNet18_Weights.DEFAULT
    model = resnet18(weights=weights)
    model.fc = torch.nn.Identity()
    model.eval()

    image = Image.open(image_path).convert("RGB")
    base_tensor = weights.transforms()(image)
    frames = build_frame_sequence(base_tensor, args.frames)

    print("Computing reference features...")
    with torch.inference_mode():
        reference_features = [model(frame) for frame in frames]

    print("Warming up model...")
    with torch.inference_mode():
        for _ in range(20):
            model(frames[0])

    print("\nRunning benchmark...")
    results = []
    for trial in range(args.trials):
        print(f"Trial {trial + 1}/{args.trials}")
        # Rotate order to reduce systematic order-related timing bias.
        shift = trial % len(STRATEGIES)
        order = list(STRATEGIES[shift:]) + list(STRATEGIES[:shift])

        for strategy in order:
            result = execute_strategy(
                strategy,
                model,
                frames,
                reference_features,
                refresh_interval=args.refresh_interval,
                threshold=args.threshold,
            )
            result["Trial"] = trial + 1
            results.append(result)

    raw_df = pd.DataFrame(results)
    summary = (
        raw_df.groupby("Strategy")
        .agg(
            Median_Total_ms=("Total_ms", "median"),
            Mean_Total_ms=("Total_ms", "mean"),
            Std_Total_ms=("Total_ms", "std"),
            Median_Per_Frame_ms=("Per_Frame_ms", "median"),
            Refreshes=("Refreshes", "median"),
            Hit_Rate=("Hit_Rate", "mean"),
            Mean_Feature_Error=("Mean_Feature_Error", "mean"),
            Max_Feature_Error=("Max_Feature_Error", "max"),
        )
        .reset_index()
    )

    baseline_rows = summary.loc[
        summary["Strategy"] == "Always Refresh", "Median_Total_ms"
    ]
    if baseline_rows.empty or baseline_rows.iloc[0] <= 0:
        raise RuntimeError("Could not calculate speedup: baseline latency is not positive.")
    baseline_ms = baseline_rows.iloc[0]
    summary["Speedup_vs_Baseline"] = baseline_ms / summary["Median_Total_ms"]

    metadata = {
        "Num_Frames": args.frames,
        "Num_Trials": args.trials,
        "Refresh_Interval": args.refresh_interval,
        "Adaptive_Threshold": args.threshold,
        "Num_Threads": args.num_threads,
        "Seed": args.seed,
        "Device": "CPU",
        "Torch_Version": torch.__version__,
        "Torchvision_Version": torchvision.__version__,
        "Image": str(image_path),
    }
    for key, value in metadata.items():
        raw_df[key] = value
        summary[key] = value

    pd.set_option("display.max_columns", None)
    pd.set_option("display.width", 240)
    print("\n===== TulipFast Benchmark Results =====")
    print(summary.round(5).to_string(index=False))
    print("\nExperimental settings:")
    for key, value in metadata.items():
        print(f"{key}: {value}")
    print("Frame generation: independent noise perturbations of one normalized image.")
    print("Important: these are synthetic frames, not real video or robot-control data.")

    results_dir = resolve_project_path(args.results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    raw_path = results_dir / f"fair_raw_{timestamp}.csv"
    summary_path = results_dir / f"fair_summary_{timestamp}.csv"
    raw_df.to_csv(raw_path, index=False)
    summary.to_csv(summary_path, index=False)

    print(f"\nRaw results saved to: {raw_path}")
    print(f"Summary saved to: {summary_path}")
    print("Benchmark complete!")


if __name__ == "__main__":
    main()
